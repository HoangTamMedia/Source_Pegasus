"""Build the world-space bitmap font: atlas plus its metrics header.

This is the font used for text drawn into the scene rather than onto the
interface - names over heads, call-outs, anything that has to sit in the world
and take a colour. The client draws that kind of text through GDI today, and GDI
is exactly what put a three hundred millisecond stall in the middle of a fight
once already; sprites cost a quad each and nothing more.

Two files come out, and they must be regenerated together:

    Pegasus\\Pegasus_Main\\pg_font.tga / .OZT    the atlas
    source\\PgFontData.h                         the glyph rectangles

The header is generated rather than parsed at runtime so there is no data file
to ship, no load order to get wrong, and a mismatch between the two is a build
error instead of garbled text on screen.

Glyphs are white. Whatever draws them multiplies by a colour, so any hue baked
in here would be multiplied twice - the design lives in the outline and the
glow, the same way the damage numbers do.
"""

import os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
SRCDIR = os.path.abspath(os.path.join(HERE, "..", "..", "..", "source"))

FONT_PATH = r"C:\Windows\Fonts\ariblk.ttf"

# Printable ASCII. Names, numbers, and the punctuation that turns up in both.
FIRST_CHAR, LAST_CHAR = 32, 126

CELL = 64                 # cell size in the atlas
COLS = 16
SUPERSAMPLE = 4
PAD = 6                   # room inside the cell for outline and glow


def write_tga_and_ozt(img, base):
    w, h = img.size
    header = bytearray(18)
    header[2] = 2
    header[12] = w & 0xFF
    header[13] = (w >> 8) & 0xFF
    header[14] = h & 0xFF
    header[15] = (h >> 8) & 0xFF
    header[16] = 32
    header[17] = 8

    px = img.load()
    body = bytearray()
    for y in range(h - 1, -1, -1):
        for x in range(w):
            r, g, b, a = px[x, y]
            body += bytes((b, g, r, a))

    tga = bytes(header) + bytes(body)
    with open(base + ".tga", "wb") as f:
        f.write(tga)
    # OpenTga swaps the extension for OZT and opens that, so the OZT is the one
    # the client will actually read.
    with open(base + ".OZT", "wb") as f:
        f.write(tga[:6] + b"\x02\x00\x00\x00" + tga[6:])
    print("  %-18s %dx%d  (.tga + .OZT)" % (os.path.basename(base), w, h))


def render_glyph(ch, size):
    """A glyph on its own tile, plus the width it actually occupies.

    Drawn large and brought down, which is what keeps the outline clean once the
    text is small on screen.
    """
    S = SUPERSAMPLE
    w = h = size * S
    tile = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(tile)

    f = ImageFont.truetype(FONT_PATH, int(h * 0.62))
    stroke = max(1, int(h * 0.045))

    bb = d.textbbox((0, 0), ch, font=f, stroke_width=stroke)
    gw = bb[2] - bb[0]
    gh = bb[3] - bb[1]

    tx = (w - gw) // 2 - bb[0]
    ty = (h - gh) // 2 - bb[1]

    # Outline, then the white body over it.
    d.text((tx, ty), ch, font=f, fill=(12, 12, 16, 255),
           stroke_width=stroke, stroke_fill=(12, 12, 16, 255))

    body = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(body).text((tx, ty), ch, font=f, fill=(255, 255, 255, 255))
    tile = Image.alpha_composite(tile, body)

    # Glow underneath, lifted from the body's own shape.
    glow = body.split()[3].filter(ImageFilter.GaussianBlur(h * 0.045))
    under = Image.new("RGBA", (w, h), (255, 255, 255, 0))
    under.putalpha(glow.point(lambda v: int(v * 0.5)))
    tile = Image.alpha_composite(under, tile)

    tile = tile.resize((size, size), Image.LANCZOS)

    # The advance is the ink plus the outline, not the cell: fixed-cell spacing
    # is what makes bitmap text look like a ransom note.
    advance = (gw / float(S)) + stroke * 2.0 / S
    if ch == " ":
        advance = size * 0.26

    return tile, advance


def main():
    count = LAST_CHAR - FIRST_CHAR + 1
    rows = (count + COLS - 1) // COLS

    atlas_w = COLS * CELL
    atlas_h = 1
    while atlas_h < rows * CELL:
        atlas_h *= 2

    atlas = Image.new("RGBA", (atlas_w, atlas_h), (0, 0, 0, 0))
    advances = []

    print("building world font")
    for i in range(count):
        ch = chr(FIRST_CHAR + i)
        tile, adv = render_glyph(ch, CELL)
        atlas.paste(tile, ((i % COLS) * CELL, (i // COLS) * CELL), tile)
        advances.append(adv)

    write_tga_and_ozt(atlas, os.path.join(HERE, "Pegasus", "Pegasus_Main", "pg_font"))

    out = os.path.join(SRCDIR, "PgFontData.h")
    with open(out, "w") as f:
        f.write("#pragma once\n\n")
        f.write("// GENERATED by Bin/Data/Interface/_build_pg_font.py - do not edit.\n")
        f.write("// Regenerate whenever pg_font.tga changes; the two belong together.\n\n")
        f.write("#define PG_FONT_FIRST_CHAR %d\n" % FIRST_CHAR)
        f.write("#define PG_FONT_LAST_CHAR  %d\n" % LAST_CHAR)
        f.write("#define PG_FONT_COLS       %d\n" % COLS)
        f.write("#define PG_FONT_CELL       %d\n" % CELL)
        f.write("#define PG_FONT_ATLAS_W    %d\n" % atlas_w)
        f.write("#define PG_FONT_ATLAS_H    %d\n\n" % atlas_h)
        f.write("// Advance width per glyph, in cell units - 1.0 is one full cell.\n")
        f.write("static const float g_afPgFontAdvance[%d] =\n{\n" % count)
        for i in range(0, count, 8):
            chunk = advances[i:i + 8]
            f.write("\t" + " ".join("%.4ff," % (a / float(CELL)) for a in chunk))
            f.write("\t// '%s'\n" % "".join(
                chr(FIRST_CHAR + i + k).replace("\\", "?") for k in range(len(chunk))))
        f.write("};\n")

    print("  %-18s %d glyphs" % ("PgFontData.h", count))


main()
